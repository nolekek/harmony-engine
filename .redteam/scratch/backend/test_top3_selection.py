import sys
sys.path.insert(0, r"D:\aitraining")
from src.harmony.core.types import Key, calculate_metric_structure, TimeSignature
from src.harmony.syntax.grammar import HarmonicGrammar
from src.harmony.solver.viterbi import ViterbiSolver

melody = [
    {"pitch": 64, "duration": "half"},
    {"pitch": 65, "duration": "half"},
    {"pitch": 67, "duration": "half"},
    {"pitch": 64, "duration": "half"},
    {"pitch": 62, "duration": "half"},
    {"pitch": 60, "duration": "whole"},
]
key = Key("C", "Major")
grammar = HarmonicGrammar(key)
plans = grammar.generate_plans(melody, key=key, max_plans=50)
print(f"Total plans generated by grammar: {len(plans)}")

solver = ViterbiSolver()
all_solutions = []
for idx, p in enumerate(plans):
    res = solver.solve(melody, p, key=key)
    if res.is_success:
        chords_str = " -> ".join(c.function for c in p)
        all_solutions.append((res.total_cost, chords_str, idx))

print(f"Total successful plans: {len(all_solutions)} out of {len(plans)}")
print("\nFirst 3 encountered in loop (current backend api logic):")
for cost, ch, idx in all_solutions[:3]:
    print(f"  Plan #{idx}: cost={cost:.2f} | {ch}")

sorted_solutions = sorted(all_solutions, key=lambda x: x[0])
print("\nActual Top 3 (global minimum cost among all evaluated plans):")
for cost, ch, idx in sorted_solutions[:3]:
    print(f"  Plan #{idx}: cost={cost:.2f} | {ch}")
