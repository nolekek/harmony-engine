"""
Lightweight Neuro-Symbolic Style Scorer for Classical SATB Harmony.
Pure Python (zero C-dependencies).

Learns stylistic transition distributions (interval movements, texture spacing,
cadence weighting) from verified Brigade dataset and scores transitions for Viterbi DP:
Cost_total = Cost_rules + lambda * Cost_neural_style
"""

import json
import math
from pathlib import Path
from typing import Any, Mapping, Sequence

from src.harmony.core.types import Voicing, to_satb


class StylePriorModel:
    """
    Probabilistic Style Transition Scorer.
    Scores SATB voice leading smoothness and composer style preferences.
    """

    def __init__(self, weight: float = 1.0):
        self.weight = weight
        # Interval transition frequencies: (ds, da, dt, db) -> count
        self.motion_counts: dict[str, int] = {}
        # Relative spacing transitions: (prev_spacing, curr_spacing) -> count
        self.spacing_counts: dict[str, int] = {}
        # Bass leap distributions
        self.bass_step_counts: dict[int, int] = {}
        self.total_transitions: int = 0
        self.vocab_size: int = 1000

        # Pre-seed with textbook classical preferences (Laplace prior)
        self._initialize_classical_priors()

    def _initialize_classical_priors(self) -> None:
        """Seeds classical Brigade voice leading priors."""
        # Preference for contrary motion (ds * db < 0) and small middle movements (da <= 2, dt <= 2)
        prototypes = [
            # (ds, da, dt, db, weight)
            (1, 0, -1, -2, 50),
            (2, 0, 0, -3, 40),
            (-1, 0, 1, 2, 50),
            (-2, 1, 0, 3, 40),
            (0, 0, 0, 0, 30),
            (1, -1, 0, 1, 25),
            (-1, 1, 0, -1, 25),
        ]
        for ds, da, dt, db, count in prototypes:
            k = f"{ds},{da},{dt},{db}"
            self.motion_counts[k] = count
            self.total_transitions += count

    def train_on_dataset(self, dataset_path: str | Path) -> int:
        """
        Learns transition priors from a JSON Lines (.jsonl) dataset generated by generate_dataset.py.
        Returns number of transitions processed.
        """
        p = Path(dataset_path)
        if not p.exists():
            return 0

        count = 0
        with open(p, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    data = json.loads(line)
                    satb_list = data.get("satb", [])
                    if len(satb_list) < 2:
                        continue

                    for i in range(1, len(satb_list)):
                        prev_v = satb_list[i - 1]
                        curr_v = satb_list[i]

                        ps, pa, pt, pb = prev_v["soprano"], prev_v["alto"], prev_v["tenor"], prev_v["bass"]
                        cs, ca, ct, cb = curr_v["soprano"], curr_v["alto"], curr_v["tenor"], curr_v["bass"]

                        ds = cs - ps
                        da = ca - pa
                        dt = ct - pt
                        db = cb - pb

                        k = f"{ds},{da},{dt},{db}"
                        self.motion_counts[k] = self.motion_counts.get(k, 0) + 1

                        self.bass_step_counts[db] = self.bass_step_counts.get(db, 0) + 1
                        self.total_transitions += 1
                        count += 1
                except Exception:
                    continue

        return count

    def score_transition(self, prev_satb: Sequence[int] | Voicing, curr_satb: Sequence[int] | Voicing) -> float:
        """
        Computes negative log-likelihood soft penalty for transition:
        Cost = -log P(transition) * weight
        Lower cost means more idiomatic/classical.
        """
        p_satb = to_satb(prev_satb)
        c_satb = to_satb(curr_satb)

        ds = c_satb[0] - p_satb[0]
        da = c_satb[1] - p_satb[1]
        dt = c_satb[2] - p_satb[2]
        db = c_satb[3] - p_satb[3]

        k = f"{ds},{da},{dt},{db}"
        count = self.motion_counts.get(k, 0)

        # Laplace smoothing: (count + 1) / (total + vocab_size)
        prob = (count + 1.0) / (self.total_transitions + self.vocab_size)
        nll = -math.log(prob)

        # Additional penalty for excessive middle voice jumps
        jump_penalty = max(0, abs(da) - 4) * 2.0 + max(0, abs(dt) - 4) * 2.0

        return (nll + jump_penalty) * self.weight

    def save_weights(self, path: str | Path) -> None:
        """Saves model priors to JSON."""
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        data = {
            "weight": self.weight,
            "total_transitions": self.total_transitions,
            "vocab_size": self.vocab_size,
            "motion_counts": self.motion_counts,
            "bass_step_counts": self.bass_step_counts,
        }
        p.write_text(json.dumps(data, indent=2), encoding="utf-8")

    @classmethod
    def load_weights(cls, path: str | Path) -> "StylePriorModel":
        """Loads model priors from JSON."""
        p = Path(path)
        model = cls()
        if not p.exists():
            return model

        data = json.loads(p.read_text(encoding="utf-8"))
        model.weight = data.get("weight", 1.0)
        model.total_transitions = data.get("total_transitions", 0)
        model.vocab_size = data.get("vocab_size", 1000)
        model.motion_counts = data.get("motion_counts", {})
        model.bass_step_counts = {int(k): v for k, v in data.get("bass_step_counts", {}).items()}
        return model
